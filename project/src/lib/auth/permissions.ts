export function can(
  actor: Actor | null | undefined,
  permission: Permission,
): boolean {
  return !!actor && ROLE_PERMISSIONS[actor.role].includes(permission);
}
export class AccessError extends Error {
  constructor(
    public status: 401 | 403,
    message: string,
  ) {
    super(message);
  }
}
/** Call from every service mutation. Domain services must supply an object rule loaded from trusted storage. */
export function authorize(
  actor: Actor | null,
  permission: Permission,
  objectRule?: (actor: Actor) => boolean,
): asserts actor is Actor {
  if (!actor) throw new AccessError(401, "Sign in to continue.");
  if (!can(actor, permission) || (objectRule && !objectRule(actor)))
    throw new AccessError(403, "You do not have permission for this action.");
}
export const notCreator = (creatorId: string) => (actor: Actor) =>
  actor.id !== creatorId;
export const ownDocument = (creatorId: string) => (actor: Actor) =>
  actor.id === creatorId;
